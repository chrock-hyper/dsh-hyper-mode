let translate: Translate = key => key

/** Install the translator bound to this plugin's locale namespace. */
export function bindTranslate(next: Translate): void {
  translate = next
}

/** Translate one key, forwarding interpolation parameters. */
export function t(key: string, params?: Record<string, unknown>): string {
  return translate(key, params)
}
